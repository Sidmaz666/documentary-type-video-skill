import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
const files = fs.readdirSync('ref').filter(f => f.startsWith('r_0')).sort();
const args = ['-y'];
for (const f of files) args.push('-i', 'ref/' + f);
const parts = files.map((f, i) => `[${i}:v]scale=480:206[v${i}]`).join(';');
const ins = files.map((f, i) => `[v${i}]`).join('');
args.push('-filter_complex', `${parts};${ins}concat=n=${files.length}:v=1:a=0,tile=10x6:padding=4:color=white[cat]`, '-map', '[cat]', '-frames:v', '1', 'sheet.png');
execFileSync('ffmpeg', args, { stdio: 'inherit' });
console.log('sheet.png written, ', files.length, 'frames');
